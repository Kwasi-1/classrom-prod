/**
 * Registers the GitHub App on an organization using GitHub's manifest flow, then saves its credentials.
 *
 *   npm run github:register -- --org <org> --url <https://your-app.onrender.com> [--name "<app name>"]
 *
 * Opens http://localhost:3456, which sends the manifest to GitHub. After you click "Create GitHub App",
 * GitHub redirects back here and the script writes (both gitignored):
 *   - render.env: every production variable, ready for Render → Environment → "Add from .env"
 *   - github-app.private-key.pem: a backup of the app's private key
 * Database URLs are copied from .env (Neon). Existing secrets in render.env are kept, not regenerated.
 */
import { exec } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { parse } from "dotenv";

const PORT = 3456;

function arg(name: string) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
}

const org = arg("org");
const appUrl = arg("url")?.replace(/\/+$/, "");
if (!org || !appUrl || !/^https:\/\//.test(appUrl)) {
  console.error('Usage: npm run github:register -- --org <org> --url <https://your-app.onrender.com> [--name "<app name>"]');
  process.exit(1);
}
// App names are unique across GitHub and limited to 34 characters.
const name = (arg("name") ?? `Classroom ${org}`).slice(0, 34);
const state = randomBytes(16).toString("hex");

const manifest = {
  name,
  url: appUrl,
  description: "Distributes coding assignments as private repos and autogrades every push.",
  public: false,
  hook_attributes: { url: `${appUrl}/api/webhooks/github`, active: true },
  redirect_url: `http://localhost:${PORT}/callback`,
  callback_urls: [`${appUrl}/api/auth/callback`],
  request_oauth_on_install: true,
  setup_on_update: false,
  default_permissions: {
    administration: "write",
    contents: "write",
    workflows: "write",
    actions: "write",
    metadata: "read",
    members: "read",
  },
  // installation / installation_repositories are delivered to every app automatically.
  default_events: ["push"],
};

const escapeHtml = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

const startPage = `<!doctype html><meta charset="utf-8"><title>Register GitHub App</title>
<body style="font-family:system-ui;max-width:560px;margin:60px auto">
<h2>Register "${escapeHtml(name)}" on ${escapeHtml(org)}</h2>
<p>Webhooks and login will point at <code>${escapeHtml(appUrl)}</code>.</p>
<form method="post" action="https://github.com/organizations/${encodeURIComponent(org)}/settings/apps/new?state=${state}">
<input type="hidden" name="manifest" value="${escapeHtml(JSON.stringify(manifest))}">
<button style="font-size:16px;padding:10px 18px">Continue to GitHub</button></form>
<p style="color:#666">On GitHub, check the name and click <b>Create GitHub App</b>.</p>`;

const donePage = (body: string) =>
  `<!doctype html><meta charset="utf-8"><body style="font-family:system-ui;max-width:560px;margin:60px auto">${body}`;

type Conversion = {
  id: number;
  slug: string;
  html_url: string;
  client_id: string;
  client_secret: string;
  webhook_secret: string;
  pem: string;
};

function writeCredentials(app: Conversion) {
  const local = existsSync(".env") ? parse(readFileSync(".env")) : {};
  const previous = existsSync("render.env") ? parse(readFileSync("render.env")) : {};
  const secret = (key: string) => previous[key] || randomBytes(32).toString("hex");
  const vars: Record<string, string> = {
    DATABASE_URL: local.DATABASE_URL ?? "",
    DATABASE_URL_UNPOOLED: local.DATABASE_URL_UNPOOLED ?? "",
    GITHUB_APP_ID: String(app.id),
    // One line with literal \n; src/lib/github.ts turns them back into newlines.
    GITHUB_APP_PRIVATE_KEY: app.pem.trim().replace(/\r?\n/g, "\\n"),
    GITHUB_APP_CLIENT_ID: app.client_id,
    GITHUB_APP_CLIENT_SECRET: app.client_secret,
    GITHUB_WEBHOOK_SECRET: app.webhook_secret,
    SESSION_SECRET: secret("SESSION_SECRET"),
    GRADER_CALLBACK_SECRET: secret("GRADER_CALLBACK_SECRET"),
    CRON_SECRET: secret("CRON_SECRET"),
    APP_URL: appUrl!,
  };
  const lines = Object.entries(vars).map(([k, v]) => `${k}=${v}`);
  writeFileSync("render.env", `# Production env for Render (generated by npm run github:register). Do not commit.\n${lines.join("\n")}\n`);
  writeFileSync("github-app.private-key.pem", app.pem);
  return vars;
}

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? "/", `http://localhost:${PORT}`);
  if (url.pathname === "/") {
    res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" }).end(startPage);
    return;
  }
  if (url.pathname !== "/callback") {
    res.writeHead(404).end();
    return;
  }
  const code = url.searchParams.get("code");
  if (!code || url.searchParams.get("state") !== state) {
    res.writeHead(400, { "Content-Type": "text/html" }).end(donePage("<h2>Invalid callback</h2><p>Start again.</p>"));
    return;
  }
  try {
    const r = await fetch(`https://api.github.com/app-manifests/${code}/conversions`, {
      method: "POST",
      headers: { Accept: "application/vnd.github+json" },
    });
    if (!r.ok) throw new Error(`GitHub returned ${r.status}: ${await r.text()}`);
    const app = (await r.json()) as Conversion;
    const vars = writeCredentials(app);
    const install = `${app.html_url}/installations/new`;
    res
      .writeHead(200, { "Content-Type": "text/html; charset=utf-8" })
      .end(donePage(`<h2>✅ "${escapeHtml(name)}" created</h2><p>Credentials saved to <code>render.env</code>. You can close this tab.</p>`));
    console.log(`\nCreated GitHub App "${app.slug}" (id ${app.id}): ${app.html_url}`);
    console.log("Wrote render.env (all production env vars) and github-app.private-key.pem.");
    console.log(`Variables: ${Object.keys(vars).join(", ")}`);
    console.log(`\nNext: paste render.env into Render → Environment → "Add from .env", then install the app:\n  ${install}`);
    server.close();
  } catch (err) {
    res.writeHead(500, { "Content-Type": "text/html" }).end(donePage(`<h2>Failed</h2><pre>${escapeHtml(String(err))}</pre>`));
    console.error(err);
    server.close();
    process.exitCode = 1;
  }
});

server.listen(PORT, () => {
  const start = `http://localhost:${PORT}/`;
  console.log(`Open ${start} to register the app on "${org}"`);
  if (process.argv.includes("--no-open")) return;
  const opener = process.platform === "win32" ? `start "" "${start}"` : process.platform === "darwin" ? `open ${start}` : `xdg-open ${start}`;
  exec(opener);
});
